def t(key: str, **kwargs: object) -> str:
    """Etkin arayüz dilinde çeviri metnini döner; bulunamazsa Türkçe veya anahtar adına düşer."""
    lang_dict = TRANSLATIONS.get(_CURRENT_LANG, TRANSLATIONS["tr"])
    template = lang_dict.get(key) or TRANSLATIONS["tr"].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def provider_label(pid: str) -> str:
    """Sağlayıcı kimliği için etkin arayüz dilindeki etiketi döner."""
    return t(f"provider_{pid}")

