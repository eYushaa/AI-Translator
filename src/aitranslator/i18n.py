from __future__ import annotations

# (kod, yerel ad, Türkçe açıklama)
UI_LANGUAGES: list[tuple[str, str, str]] = [
    ("tr", "Türkçe", "Türkçe"),
    ("en", "English", "İngilizce"),
    ("fr", "Français", "Fransızca"),
    ("de", "Deutsch", "Almanca"),
    ("ru", "Русский", "Rusça"),
    ("ar", "العربية", "Arapça"),
    ("zh-CN", "简体中文", "Çince (Basitleştirilmiş)"),
    ("ja", "日本語", "Japonca"),
    ("ko", "한국어", "Korece"),
    ("es", "Español", "İspanyolca"),
]

SUPPORTED_UI_LANG_CODES: tuple[str, ...] = tuple(code for code, _, _ in UI_LANGUAGES)

_CURRENT_LANG: str = "tr"


def normalize_ui_lang(code: str) -> str:
    """Kullanıcı/ayar dil kodunu desteklenen arayüz dili koduna dönüştürür."""
    if not code:
        return "tr"
    c = code.strip().replace("_", "-")
    if c in SUPPORTED_UI_LANG_CODES:
        return c
    low = c.lower()
    for sup in SUPPORTED_UI_LANG_CODES:
        if sup.lower() == low:
            return sup
    if low.startswith("zh"):
        return "zh-CN"
    base = low.split("-")[0]
    for sup in SUPPORTED_UI_LANG_CODES:
        if sup.lower() == base:
            return sup
    return "tr"


def set_ui_language(code: str) -> str:
    """Etkin arayüz dilini değiştirir ve normalize edilmiş kodu döner."""
    global _CURRENT_LANG
    _CURRENT_LANG = normalize_ui_lang(code)
    return _CURRENT_LANG


def get_ui_language() -> str:
    """Etkin arayüz dilini döner."""
    return _CURRENT_LANG


def is_rtl(code: str | None = None) -> bool:
    """Belirtilen (veya etkin) dil sağdan sola (RTL) mı?"""
    lang = normalize_ui_lang(code or _CURRENT_LANG)
    return lang == "ar"


